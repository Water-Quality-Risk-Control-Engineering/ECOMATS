#!/usr/bin/env python3
"""
Evaluation Tool.
Implements evaluation result judgment logic based on core standards.
"""

import json
import re

class EvaluationTool:
    @staticmethod
    def analyze_evaluation_result(evaluation_report):
        """
        Analyze evaluation report and determine if redesign is needed.
        
        Args:
            evaluation_report (str): Evaluation report generated by technical assessment expert
            
        Returns:
            dict: Dictionary containing judgment result and suggestions
        """
        analysis_result = {
            "core_standards_met": True,
            "need_redesign": False,
            "reason": "",
            "suggestions": ""
        }
        
        try:
            # Try to parse JSON format evaluation report
            if isinstance(evaluation_report, str):
                # Extract JSON content
                json_match = re.search(r'\{.*\}', evaluation_report, re.DOTALL)
                if json_match:
                    report_data = json.loads(json_match.group())
                            
                    # Check core standards (catalytic performance)
                    if "results" in report_data:
                        for result in report_data["results"]:
                            if "scores" in result:
                                # Catalytic performance is first scoring dimension (index 0), 50% weight
                                catalytic_performance = result["scores"][0]
                                if catalytic_performance < 6:  # Below 6 is considered substandard
                                    analysis_result["core_standards_met"] = False
                                    analysis_result["need_redesign"] = True
                                    analysis_result["reason"] = f"Catalytic performance score too low: {catalytic_performance}/10"
                                    analysis_result["suggestions"] = "Suggest redesigning material structure, optimizing active sites and reaction pathways"
                                    break
                            
                    # Check if any dimension has too low score
                    if analysis_result["core_standards_met"]:
                        for result in report_data["results"]:
                            if "scores" in result:
                                scores = result["scores"]
                                for i, score in enumerate(scores):
                                    if score < 3:  # Any dimension below 3
                                        dimension_names = ["Catalytic Performance", "Economic Feasibility", "Environmental Friendliness", "Technical Feasibility", "Structural Rationality"]
                                        analysis_result["core_standards_met"] = False
                                        analysis_result["need_redesign"] = True
                                        analysis_result["reason"] = f"{dimension_names[i]} score too low: {score}/10"
                                        analysis_result["suggestions"] = f"Suggest optimizing and improving {dimension_names[i]}"
                                        break
                                if analysis_result["need_redesign"]:
                                    break
                else:
                    # Non-JSON format handling
                    analysis_result["core_standards_met"] = True
                    analysis_result["need_redesign"] = False
                    analysis_result["reason"] = "Unable to parse detailed evaluation report format"
                    analysis_result["suggestions"] = "Suggest providing structured evaluation report for more accurate analysis"
                
        except json.JSONDecodeError:
            # JSON parsing failure handling
            analysis_result["core_standards_met"] = True
            analysis_result["need_redesign"] = False
            analysis_result["reason"] = "Evaluation report format is non-standard"
            analysis_result["suggestions"] = "Suggest providing standard JSON format evaluation report"
        except Exception as e:
            # Other exception handling
            analysis_result["core_standards_met"] = True
            analysis_result["need_redesign"] = False
            analysis_result["reason"] = f"Error occurred during analysis: {str(e)}"
            analysis_result["suggestions"] = "Please check evaluation report content"
        
        return analysis_result
    
    @staticmethod
    def check_core_standards(evaluation_report):
        """
        Check if core standards (catalytic performance and structural rationality) meet requirements.
        
        Args:
            evaluation_report (str): Evaluation report
            
        Returns:
            bool: True if core standards are met, False otherwise
        """
        try:
            # Try to parse JSON format evaluation report
            if isinstance(evaluation_report, str):
                json_match = re.search(r'\{.*\}', evaluation_report, re.DOTALL)
                if json_match:
                    report_data = json.loads(json_match.group())
                    
                    # Check core standards
                    if "results" in report_data:
                        for result in report_data["results"]:
                            if "scores" in result:
                                # Catalytic performance is first dimension (index 0), structural rationality is fifth (index 4)
                                catalytic_performance = result["scores"][0]
                                structural_rationality = result["scores"][4]
                                
                                # Core standards: both catalytic performance and structural rationality should be >=6
                                if catalytic_performance < 6 or structural_rationality < 6:
                                    return False
                    return True
                else:
                    # Non-JSON format, default to pass
                    return True
            else:
                # Non-string format, default to pass
                return True
                
        except Exception:
            # On exception, default to pass
            return True